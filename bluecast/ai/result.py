"""Result container for BlueCastAI runs."""

import json
import logging
from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional, Union

import numpy as np
import pandas as pd

logger = logging.getLogger(__name__)


@dataclass
class BlueCastAIResult:
    """Result of a BlueCastAI run.

    Contains the trained pipeline, generated code, metrics, a polished
    report, and a full structured log of what each agent did and why.

    :param pipeline: The trained BlueCast pipeline, ready for .predict().
    :param pipeline_code: Python code that reproduces the pipeline (standalone).
    :param feature_engineering_code: Python code for the feature engineering steps.
    :param metrics: Evaluation metrics from the best run.
    :param data_profile: Summary of dataset characteristics.
    :param run_history: Results from each build-evaluate iteration.
    :param agent_log: Flat log of all agent actions (list of strings).
    :param class_problem: Detected or configured problem type.
    :param report_markdown: Polished Markdown report generated by the Reporter agent.
    :param structured_log: Full structured log with timestamps and metadata.
    """

    pipeline: Optional[Any] = None
    pipelines: List[Any] = field(default_factory=list)
    hill_climbing_ensemble: Optional[Any] = None
    pipeline_code: str = ""
    feature_engineering_code: str = ""
    metrics: Dict[str, Any] = field(default_factory=dict)
    data_profile: Optional[Dict[str, Any]] = None
    run_history: List[Dict[str, Any]] = field(default_factory=list)
    agent_log: List[str] = field(default_factory=list)
    class_problem: str = "binary"
    report_markdown: str = ""
    structured_log: List[Any] = field(default_factory=list)

    def predict(self, df: pd.DataFrame) -> Union[np.ndarray, pd.Series]:
        """Predict using the trained pipeline.

        For classification pipelines this returns class labels (not probabilities).
        For regression pipelines this returns continuous predictions.
        """
        if getattr(self, "hill_climbing_ensemble", None) is not None:
            all_preds = []
            for p in self.pipelines:
                p_preds = p.predict(df)
                if isinstance(p_preds, tuple) and len(p_preds) == 2:
                    p_preds = p_preds[1]
                all_preds.append(p_preds.values if hasattr(p_preds, "values") else p_preds)
            return self.hill_climbing_ensemble.predict(all_preds)
            
        if getattr(self, "pipelines", None):
            all_preds = []
            for p in self.pipelines:
                p_preds = p.predict(df)
                if isinstance(p_preds, tuple) and len(p_preds) == 2:
                    p_preds = p_preds[1]
                all_preds.append(p_preds)
            return np.mean(all_preds, axis=0)
            
            
        if self.pipeline is None:
            raise RuntimeError("No trained pipeline available.")

        preds = self.pipeline.predict(df)

        # BlueCast and BlueCastCV (classification) return a (probas, classes) tuple.
        # BlueCastRegression and BlueCastCVRegression return a single object (Series/ndarray).
        if isinstance(preds, tuple) and len(preds) == 2:
            return preds[1]  # Return class labels

        return preds

    def predict_proba(self, df: pd.DataFrame) -> Union[np.ndarray, pd.Series]:
        """Predict class probabilities using the trained pipeline.

        Only applicable for classification problems.
        """
        if getattr(self, "hill_climbing_ensemble", None) is not None:
            all_preds = []
            for p in self.pipelines:
                if hasattr(p, "predict_proba"):
                    p_preds = p.predict_proba(df)
                else:
                    p_preds = p.predict(df)
                    if isinstance(p_preds, tuple) and len(p_preds) == 2:
                        p_preds = p_preds[0]
                    else:
                        raise AttributeError("The underlying pipeline does not support probability prediction.")
                all_preds.append(p_preds.values if hasattr(p_preds, "values") else p_preds)
            return self.hill_climbing_ensemble.predict(all_preds)

        if getattr(self, "pipelines", None):
            all_preds = []
            for p in self.pipelines:
                if hasattr(p, "predict_proba"):
                    p_preds = p.predict_proba(df)
                else:
                    p_preds = p.predict(df)
                    if isinstance(p_preds, tuple) and len(p_preds) == 2:
                        p_preds = p_preds[0]
                    else:
                        raise AttributeError("The underlying pipeline does not support probability prediction.")
                all_preds.append(p_preds)
            return np.mean(all_preds, axis=0)

        if self.pipeline is None:
            raise RuntimeError("No trained pipeline available.")

        # If the pipeline has predict_proba, use it (standard for BlueCast/CastCV)
        if hasattr(self.pipeline, "predict_proba"):
            return self.pipeline.predict_proba(df)

        # Fallback for pipelines where predict returns the (probas, classes) tuple
        preds = self.pipeline.predict(df)
        if isinstance(preds, tuple) and len(preds) == 2:
            return preds[0]  # Return probabilities

        raise AttributeError("The underlying pipeline does not support probability prediction.")

    def save_code(self, path: str) -> None:
        """Save the generated pipeline code to a .py file."""
        full_code = []
        full_code.append('"""Auto-generated by BlueCastAI."""\n')
        full_code.append("import numpy as np")
        full_code.append("import pandas as pd\n")

        if self.feature_engineering_code:
            full_code.append("# --- Feature Engineering ---")
            full_code.append(self.feature_engineering_code)
            full_code.append("")

        if self.pipeline_code:
            full_code.append("# --- Pipeline ---")
            full_code.append(self.pipeline_code)

        with open(path, "w") as f:
            f.write("\n".join(full_code))
        logger.info(f"Pipeline code saved to {path}")

    def save_report(self, path: str) -> None:
        """Save the Reporter agent's Markdown report to a file.

        :param path: File path (e.g. 'report.md').
        """
        with open(path, "w") as f:
            f.write(self.report_markdown)
        logger.info(f"Report saved to {path}")

    def save_log(self, path: str) -> None:
        """Save the full structured agent log to a JSON file.

        :param path: File path (e.g. 'agent_log.json').
        """
        entries = []
        for entry in self.structured_log:
            entries.append(
                {
                    "timestamp": getattr(entry, "timestamp", 0),
                    "agent": getattr(entry, "agent", ""),
                    "event_type": getattr(entry, "event_type", ""),
                    "content": getattr(entry, "content", ""),
                    "metadata": getattr(entry, "metadata", None),
                }
            )
        with open(path, "w") as f:
            json.dump(entries, f, indent=2, default=str)
        logger.info(f"Structured log saved to {path}")

    def show_report(self) -> None:
        """Print a human-readable summary of the BlueCastAI run."""
        if self.report_markdown:
            print(self.report_markdown)
            return

        print("=" * 60)
        print("BlueCastAI Run Report")
        print("=" * 60)
        print(f"Problem type: {self.class_problem}")

        if self.metrics:
            print("\nBest metrics:")
            for k, v in self.metrics.items():
                if isinstance(v, float):
                    print(f"  {k}: {v:.4f}")
                elif isinstance(v, (int, str)):
                    print(f"  {k}: {v}")

        if self.run_history:
            print(f"\nIterations: {len(self.run_history)}")
            for i, run in enumerate(self.run_history):
                m = run.get("metrics", {})
                status = "OK" if run.get("success", False) else "FAILED"
                print(f"  Run {i + 1} [{status}]: {m}")

        if self.feature_engineering_code:
            print("\nFeature engineering applied: Yes")
        else:
            print("\nFeature engineering applied: No")

        if self.pipeline_code:
            print(f"\nGenerated pipeline code: {len(self.pipeline_code)} chars")
            print("  Use result.save_code('pipeline.py') to export")

        print(f"\nAgent log ({len(self.agent_log)} entries):")
        for entry in self.agent_log[-10:]:
            print(f"  {entry}")
        if len(self.agent_log) > 10:
            print(f"  ... and {len(self.agent_log) - 10} more entries")

        print("\nExport options:")
        print("  result.save_report('report.md')   # Markdown report")
        print("  result.save_code('pipeline.py')    # Reproducible code")
        print("  result.save_log('agent_log.json')  # Full agent log")
        print()

    def __repr__(self) -> str:
        status = "trained" if self.pipeline is not None else "no pipeline"
        n_runs = len(self.run_history)
        has_report = "yes" if self.report_markdown else "no"
        return (
            f"BlueCastAIResult(status={status}, runs={n_runs}, "
            f"metrics={self.metrics}, report={has_report})"
        )
